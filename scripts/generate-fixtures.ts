/**
 * Regenerates the files in sample_data/.   Run with:  npm run fixtures
 *
 * The EXPECTED numbers for the scripted session are computed here directly from the script
 * (counting presses and taking a median of the planned reaction times). They do NOT come from the
 * game engine, so the test in tests/scenario.test.ts is an independent check of the engine.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateSequence } from '../src/engine/sequence';

const SEED = 20261020;
const TRIAL_COUNT = 30;
const TARGET_FREQUENCY = 0.3;

const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'sample_data');
mkdirSync(outDir, { recursive: true });

const trials = generateSequence(SEED, TRIAL_COUNT, TARGET_FREQUENCY);

// ---- 1. the seeded 30-trial sequence ------------------------------------------------------
const sequence = {
  description: 'Seeded 30-trial sequence (30% targets = 9 targets). Generated by generateSequence().',
  seed: SEED,
  trialCount: TRIAL_COUNT,
  targetFrequency: TARGET_FREQUENCY,
  targetCount: trials.filter((t) => t.isTarget).length,
  trials,
};
writeFileSync(join(outDir, 'trial_sequence_seed_20261020.json'), JSON.stringify(sequence, null, 2) + '\n');

// ---- 2. a scripted player + hand-computed expected result ----------------------------------
const MISSED_TARGET_ORDINALS = new Set([2, 6]); // 3rd and 7th target are not pressed
const FALSE_ALARM_NON_TARGET_ORDINALS = new Set([2, 9]); // 3rd and 10th non-target are pressed

let targetOrdinal = 0;
let nonTargetOrdinal = 0;
const actions: { trialIndex: number; press: boolean; offsetMs: number }[] = [];
const hitRts: number[] = [];
let misses = 0;
let falseAlarms = 0;

for (const trial of trials) {
  if (trial.isTarget) {
    if (MISSED_TARGET_ORDINALS.has(targetOrdinal)) {
      misses++;
      actions.push({ trialIndex: trial.index, press: false, offsetMs: 0 });
    } else {
      const rt = 280 + 25 * targetOrdinal;
      hitRts.push(rt);
      actions.push({ trialIndex: trial.index, press: true, offsetMs: rt });
    }
    targetOrdinal++;
  } else {
    if (FALSE_ALARM_NON_TARGET_ORDINALS.has(nonTargetOrdinal)) {
      falseAlarms++;
      actions.push({ trialIndex: trial.index, press: true, offsetMs: 250 });
    } else {
      actions.push({ trialIndex: trial.index, press: false, offsetMs: 0 });
    }
    nonTargetOrdinal++;
  }
}

const sorted = [...hitRts].sort((a, b) => a - b);
const mid = Math.floor(sorted.length / 2);
const median = sorted.length % 2 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2;

const scripted = {
  description:
    'A scripted player. offsetMs is the time after symbol onset at which the key is pressed. ' +
    'Targets #3 and #7 are missed; non-targets #3 and #10 get a false alarm.',
  seed: SEED,
  actions,
  expected: {
    targetCount: targetOrdinal,
    nonTargetCount: nonTargetOrdinal,
    hits: hitRts.length,
    misses,
    falseAlarms,
    correctWithholds: nonTargetOrdinal - falseAlarms,
    targetAccuracyPct: Math.round((hitRts.length / targetOrdinal) * 1000) / 10,
    medianRtMs: median,
  },
};
writeFileSync(join(outDir, 'scripted_session.json'), JSON.stringify(scripted, null, 2) + '\n');

console.log('Wrote sample_data/trial_sequence_seed_20261020.json and sample_data/scripted_session.json');
console.log('Expected:', scripted.expected);
